using AegisDocs.UI.Models;
using System.Collections.Generic;

namespace AegisDocs.UI.Services;

public static class PromptProvider
{
    private const string JsonFormatRequirement = @"
        ВОЯ ЗАДАЧА — ВЕРНУТЬ ОТВЕТ ИСКЛЮЧИТЕЛЬНО В ФОРМАТЕ JSON.
        Не пиши никаких пояснений или текста до и после JSON.
        Обязательно классифицируй каждую ошибку в поле Category.
        КРИТИЧЕСКИ ВАЖНЫЕ ПРАВИЛА ДЛЯ СТРОК:
        1. В поле ""OriginalText"" копируй ТОЧНЫЙ фрагмент из документа символ в символ.
        2. ЗАПРЕЩЕНО оборачивать значение в дополнительные внешние кавычки (пиши текст напрямую внутри строки JSON).
        3. ЗАПРЕЩЕНО менять регистр букв в OriginalText (если в тексте 'Оплата', не пиши 'ОПЛАТА').
        4. Выводи ТОЛЬКО РЕАЛЬНЫЕ ошибки, присутствующие в тексте.
        5. КАК ТОЛЬКО ОШИБКИ ЗАКОНЧИЛИСЬ — ЗАКРОЙ МАССИВ СИМВОЛОМ ] И ОСТАНОВИСЬ!
        Формат ответа должен быть строго таким:
        [
          {
            ""Category"": ""Название категории"",
            ""OriginalText"": ""ошибочный фрагмент из текста"",
            ""CorrectedText"": ""исправленный вариант"",
            ""Reason"": ""почему это ошибка""
          }
        ]";

    public static List<PromptTemplate> GetDefaultTemplates()
    {
        return new List<PromptTemplate>
        {
            new PromptTemplate(
                "Глубокий аудит (Все ошибки)",
                "Ты строгий юрист-аудитор. Проверь текст договора на наличие любых ошибок: логических, финансовых, фактических, в датах и реквизитах. ВНИМАНИЕ: Если ты нашел все ошибки, НЕМЕДЛЕННО остановись и закрой массив символом ]. НЕ повторяй одну и ту же ошибку дважды!" + JsonFormatRequirement
            ),

            new PromptTemplate(
                "Проверка дат, сроков и сумм",
                "Ты математик-аудитор. Твоя ЕДИНСТВЕННАЯ задача — проверить все даты, сроки, проценты и суммы в тексте. Ищи логические и математические нестыковки. НЕ придумывай новые условия. ВНИМАНИЕ: Если ты нашел все ошибки, НЕМЕДЛЕННО остановись и закрой массив символом ]. НЕ повторяй одну и ту же ошибку дважды! " + JsonFormatRequirement
            ),

            new PromptTemplate(
                "Аудит реквизитов и сторон",
                "Ты юрист-регистратор. Проверь ТОЛЬКО данные сторон (ИНН, КПП, расчетные счета, паспорта, ФИО и должности). Если данных не хватает или есть опечатки - укажи это. Если все реквизиты верны, верни пустой массив []. " + JsonFormatRequirement
            ),
            new PromptTemplate(
                "Тест",
                "Роль:ты – юридический ассистент по вычитке юридических документов. Твоя задача – провести детальный анализ юридического документа и выявить ошибки в передаче материала. Проблема:Юридический документ правильный по смыслу, но содержит множество мелких, но критически важных расхождений: разный регистр (ПРОПИСНЫЕ / строчные), пропуски частей названий (например, «Частная компания с ограниченной ответственностью»), разное написание имён и адресов. Задача: Исправить регистр букв (Caps Lock, заглавные/строчные), орфографию и пунктуацию, единообразие терминов (одинаковое написание одного названия во всех документах), оформление адресов (город, штат, почтовый индекс, страна). ВНИМАНИЕ: Если ты нашел все ошибки, НЕМЕДЛЕННО остановись и закрой массив символом ]. НЕ повторяй одну и ту же ошибку дважды!" + JsonFormatRequirement
            )
        };
    }
}
